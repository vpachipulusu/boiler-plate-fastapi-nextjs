type OptionalOfferKey =
  | 'status'
  | 'featured'
  | 'postage'
  | 'requiresCard'
  | 'subscriptionTerms'
  | 'endAt';

type FixedOfferKey = 'steps' | 'demo' | 'source' | 'destinationUrl';

type OfferInput = Omit<Offer, OptionalOfferKey | FixedOfferKey> &
  Partial<Pick<Offer, OptionalOfferKey>>;

/** Fills the defaults shared by every fixture offer so each entry only states what differs. */
function defineOffer(input: OfferInput): Offer {
  return {
    status: 'published',
    featured: false,
    postage: { kind: 'free' },
    requiresCard: false,
    subscriptionTerms: null,
    endAt: null,
    ...input,
    steps: STEPS_BY_TYPE[input.offerType].map((step) => ({ ...step })),
    demo: true,
    source: 'fixture',
    destinationUrl: null,
  };
}

